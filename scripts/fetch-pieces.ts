// One-off generator: downloads the lichess "staunty" piece set (sadsnake1, CC BY-NC-SA 4.0)
// and writes src/render/pieces.ts. Run: bun scripts/fetch-pieces.ts
const BASE = 'https://raw.githubusercontent.com/lichess-org/lila/master/public/piece/staunty'
const names = ['wK', 'wQ', 'wR', 'wB', 'wN', 'wP', 'bK', 'bQ', 'bR', 'bB', 'bN', 'bP']
let symbols = ''
for (const n of names) {
  const svg = (await (await fetch(`${BASE}/${n}.svg`)).text()).trim()
  const open = /^<svg\b([^>]*)>/.exec(svg)
  if (!open || !svg.endsWith('</svg>')) throw new Error(`unexpected svg for ${n}`)
  const viewBox = /viewBox="([^"]+)"/.exec(open[1]!)?.[1]
  if (!viewBox) throw new Error(`no viewBox for ${n}`)
  // Presentation attributes on the root <svg> (fill-rule etc.) are inherited by children via <symbol>.
  const inner = svg.slice(open[0].length, -'</svg>'.length)
  if (/\bid="/.test(inner)) throw new Error(`${n} uses ids; would clash when inlined`)
  symbols += `<symbol id="${n}" viewBox="${viewBox}" fill-rule="evenodd" clip-rule="evenodd">${inner}</symbol>`
}
const out = `// GENERATED by scripts/fetch-pieces.ts. Do not edit.
export const ATTRIBUTION =
  'Chess pieces: "Staunty" by sadsnake1 (lichess.org), licensed CC BY-NC-SA 4.0'

/** Shared <defs> content: one <symbol> per piece, id = color letter + piece letter (wK, bP, ...). */
export const PIECE_SYMBOLS = ${JSON.stringify(symbols)}
`
await Bun.write(new URL('../src/render/pieces.ts', import.meta.url), out)
console.log('wrote', out.length, 'bytes')
